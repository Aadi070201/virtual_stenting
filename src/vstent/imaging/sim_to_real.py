"""Sim-to-real segmentation comparison (P8) → ``reports/sim_to_real.md``.

The baseline segmenter (M5, ARCADE only) and the model trained with rendered angiograms added
(:mod:`vstent.data.synth_angio`) are evaluated on the same images: ARCADE syntax val and test
and the rendered test split. The adoption rule was pre-registered in docs/PLAN.md: the new model
replaces the product's segmenter only if its mean ARCADE test Dice is higher and the lower bound
of the 95% bootstrap interval of the paired per-image difference is above −0.01.
"""

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import torch

from vstent import DISCLAIMER, __version__
from vstent.config import CONFIG_FILENAME, git_info, load_config
from vstent.data.arcade import load_split
from vstent.data.synth_angio import load_synth_split
from vstent.imaging.seg_train import (
    SegConfig,
    load_checkpoint,
    predict_probs,
    resolve_device,
    validation_tensors,
)
from vstent.imaging.segment import THRESHOLD, dice_score, probability_to_image

REPORT = "sim_to_real"
MARGIN = 0.01  # adoption: lower bound of the paired difference's 95% interval above −MARGIN
N_BOOT = 10_000
SEED = 0


def _dice(model, images, masks, size: int, batch: int, device) -> np.ndarray:
    x, _ = validation_tensors(images, masks, size)
    prob = predict_probs(model, x, batch, device, amp=False)
    prob = np.stack([probability_to_image(p, im.shape) for p, im in zip(prob, images, strict=True)])
    return dice_score(prob >= THRESHOLD, masks)


def paired_interval(diff: np.ndarray, n_boot: int = N_BOOT, seed: int = SEED):
    """Mean and 95% percentile-bootstrap interval of per-image paired differences."""
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, diff.size, (n_boot, diff.size))
    boots = diff[idx].mean(axis=1)
    lo, hi = np.percentile(boots, [2.5, 97.5])
    return float(diff.mean()), float(lo), float(hi)


def compare_runs(
    base_run: str | Path,
    new_run: str | Path,
    synth_dir: str | Path,
    report_dir: str | Path = "reports",
    *,
    device: str = "auto",
    max_images: int | None = None,
) -> dict[str, Any]:
    """Evaluate both runs on ARCADE val / test and the rendered test split; write the report."""
    base_run, new_run, report_dir = Path(base_run), Path(new_run), Path(report_dir)
    cfg = load_config(new_run / CONFIG_FILENAME, SegConfig)
    dev = resolve_device(device)
    size, batch = cfg.model.image_size, cfg.train.eval_batch_size
    data = {}
    for split in ("val", "test"):
        s = load_split(cfg.raw_dir, "syntax", split, max_images)
        data[f"ARCADE {split}"] = (s.images, s.masks)
    data["rendered test"] = load_synth_split(synth_dir, "test", max_images)
    dice: dict[str, dict[str, np.ndarray]] = {}
    for name, run in (("baseline", base_run), ("with rendered", new_run)):
        model = load_checkpoint(run, dev)
        with torch.no_grad():
            dice[name] = {k: _dice(model, im, mk, size, batch, dev) for k, (im, mk) in data.items()}
        del model
    rows = []
    for k in data:
        b, n = dice["baseline"][k], dice["with rendered"][k]
        mean, lo, hi = paired_interval(n - b)
        rows.append({"split": k, "n": int(b.size), "baseline": float(b.mean()),
                     "new": float(n.mean()), "diff": mean, "lo": lo, "hi": hi,
                     "baseline_p10": float(np.percentile(b, 10)),
                     "new_p10": float(np.percentile(n, 10))})  # fmt: skip
    test = next(r for r in rows if r["split"] == "ARCADE test")
    adopt = test["new"] > test["baseline"] and test["lo"] > -MARGIN
    provenance = {**git_info(), "vstent_version": __version__,
                  "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
                  "device": str(dev), "torch": torch.__version__}  # fmt: skip
    report = {"rows": rows, "adopt": adopt, "base_run": base_run.as_posix(),
              "new_run": new_run.as_posix(), "synth_dir": Path(synth_dir).as_posix(),
              "provenance": provenance}  # fmt: skip
    report_dir.mkdir(parents=True, exist_ok=True)
    (report_dir / f"{REPORT}.json").write_text(json.dumps(report, indent=2) + "\n",
                                               encoding="utf-8", newline="\n")  # fmt: skip
    (report_dir / f"{REPORT}.md").write_text(_markdown(report, cfg), encoding="utf-8",
                                             newline="\n")  # fmt: skip
    return report


def _markdown(report: dict[str, Any], cfg: SegConfig) -> str:
    syn = cfg.synthetic
    lines = [
        "# Sim-to-real: segmentation trained with rendered angiograms (P8)",
        "",
        f"> **{DISCLAIMER}**",
        "",
        "Generated by `vstent sim-to-real-report`. Do not edit by hand.",
        "",
        "Baseline: the M5 segmenter, trained on ARCADE's 1,000 syntax training images. New: the "
        "same configuration (seed, schedule, early stopping on ARCADE val) with "
        f"{syn.n_train if syn else 0} rendered angiograms (`vstent synth-angio`, "
        "`reports/synth_angio_card.md`) added. Dice per image at probability ≥ "
        f"{THRESHOLD}; paired difference = new − baseline per image, with a 95% percentile "
        f"bootstrap interval ({N_BOOT:,} resamples).",
        "",
        "**Labels differ by design.** ARCADE annotates the SYNTAX segments of each image, often "
        "not every major vessel in view; the rendered labels mark every vessel ≥ 1.5 mm "
        "(pre-registered). On ARCADE, a segmenter that finds unannotated vessels is scored down "
        "for it.",
        "",
        "| Images | n | Baseline mean Dice | New mean Dice | Difference (95% interval) | "
        "Baseline 10th pct | New 10th pct |",
        "|---|---:|---:|---:|---:|---:|---:|",
        *(f"| {r['split']} | {r['n']} | {r['baseline']:.4f} | {r['new']:.4f} | "
          f"{r['diff']:+.4f} ({r['lo']:+.4f} to {r['hi']:+.4f}) | {r['baseline_p10']:.3f} | "
          f"{r['new_p10']:.3f} |" for r in report["rows"]),
        "",
        "**Adoption rule** (pre-registered in docs/PLAN.md): the new model replaces the product's "
        "segmenter only if its mean ARCADE test Dice is higher and the lower bound of the "
        f"interval is above −{MARGIN:g}. **Outcome: "
        + ("adopted" if report["adopt"] else "not adopted; the M5 segmenter stays") + ".**",
        "",
        "ARCADE val chose both models' epochs, so its numbers are optimistic; ARCADE test was "
        "evaluated once for this comparison. The rendered test split comes from the same "
        "generator as the new model's training images.",
        "",
        f"Runs: baseline `{report['base_run']}`, new `{report['new_run']}`; rendered data "
        f"`{report['synth_dir']}`. Commit `{report['provenance']['git_commit']}` (dirty: "
        f"{report['provenance']['git_dirty']}), created {report['provenance']['created_utc']}.",
        "",
    ]  # fmt: skip
    return "\n".join(lines)
