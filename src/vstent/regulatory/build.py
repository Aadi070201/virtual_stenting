"""Render the generated regulatory documents (``vstent regulatory``).

Sources (hand-maintained): ``docs/regulatory/{requirements,hazards,soup}.yaml`` and
``uv.lock``. Outputs (never edited by hand): ``REQUIREMENTS.md``, ``HAZARD_ANALYSIS.md``,
``TRACEABILITY.md``, ``SOUP.md`` and the CycloneDX SBOM ``sbom.cdx.json``. Every output is
deterministic (no dates or commits), so a test can check that the committed files match
their sources.
"""

from collections import Counter
from pathlib import Path

from vstent import DISCLAIMER
from vstent.regulatory.soup import (
    PLATFORMS,
    SOUP_FILE,
    Lock,
    check_soup,
    load_soup,
    normalise,
    python_version,
    release_packages,
    sbom_json,
    software_items,
    third_party_imports,
)
from vstent.regulatory.trace import (
    HAZARDS_FILE,
    KINDS,
    REQUIREMENTS_FILE,
    Hazard,
    Requirement,
    Trace,
    load_trace,
)

REG_DIR = Path("docs/regulatory")
DRAFT = (
    f"> **{DISCLAIMER}** Draft regulatory groundwork for review by a qualified person; not "
    "regulatory advice."
)
UP = "../../"  # from docs/regulatory/ to the repository root


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]


def _head(title: str, sources: str) -> list[str]:
    return [
        f"# {title}",
        "",
        DRAFT,
        "",
        f"Generated by `vstent regulatory` from {sources}. Do not edit by hand.",
        "",
    ]


def _code(refs: list[str]) -> str:
    return ", ".join(f"`{r}`" for r in refs)


def _test_link(ref: str) -> str:
    path, _, name = ref.partition("::")
    return f"[`{name}`]({UP}{path})"


def _verification(r: Requirement) -> list[str]:
    out = []
    if r.tests:
        out.append("tests: " + ", ".join(_test_link(t) for t in r.tests))
    if r.reports:
        out.append("reports: " + ", ".join(f"[{Path(p).name}]({UP}{p})" for p in r.reports))
    if r.inspection:
        out.append(f"inspection: {' '.join(r.inspection.split())}")
    return out


def _status(r: Requirement) -> str:
    if r.gap and not (r.tests or r.reports or r.inspection):
        return "gap"
    if r.tests or r.reports:
        return "verified" if not r.gap else "partly verified"
    return "inspection only"


def render_requirements(trace: Trace) -> str:
    reqs = trace.requirements
    lines = _head("Software requirements (draft)", f"`{REQUIREMENTS_FILE.as_posix()}`")
    status = Counter(_status(r) for r in reqs)
    lines += [
        "IEC 62304 §5.2. Each requirement names the code that implements it and how it is "
        "verified; `vstent regulatory` fails if a referenced file, function, test or report "
        "does not exist. Risk controls are the requirements that hazards "
        "([HAZARD_ANALYSIS.md](HAZARD_ANALYSIS.md)) list as their controls.",
        "",
        f"**{len(reqs)} requirements:** " + ", ".join(
            f"{status[k]} {k}" for k in ("verified", "partly verified", "inspection only", "gap")
            if status[k]
        ) + f"; {sum(bool(trace.controls_of(r.id)) for r in reqs)} are risk controls.",
        "",
    ]  # fmt: skip
    rows = []
    for kind, label in KINDS.items():
        group = [r for r in reqs if r.kind == kind]
        if group:
            rows.append([label, ", ".join(r.id for r in group)])
    lines += _table(["Group", "Requirements"], rows) + [""]
    for kind, label in KINDS.items():
        group = [r for r in reqs if r.kind == kind]
        if not group:
            continue
        lines += [f"## {label}", ""]
        for r in group:
            lines += [f"### {r.id}: {r.title}", "", " ".join(r.text.split()), ""]
            lines.append(f"- **Code:** {_code(r.code)}")
            lines += [f"- **Verified by** {v}" for v in _verification(r)]
            if r.gap:
                lines.append(f"- **Gap:** {' '.join(r.gap.split())}")
            hz = trace.controls_of(r.id)
            if hz:
                lines.append(f"- **Risk control for:** {', '.join(hz)}")
            lines.append(f"- **Status:** {_status(r)}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _risk(trace: Trace, s: int, p: int) -> str:
    return f"{s * p} {trace.policy.level(s, p)}"


def render_hazards(trace: Trace) -> str:
    pol, hz = trace.policy, trace.hazards
    req = {r.id: r for r in trace.requirements}
    lines = _head("Hazard analysis (ISO 14971 draft)", f"`{HAZARDS_FILE.as_posix()}`")
    before = Counter(pol.level(h.severity, h.probability) for h in hz)
    after = Counter(pol.level(h.severity, h.residual_probability) for h in hz)

    def counts(c: Counter) -> str:
        return ", ".join(f"{c[k]} {k}" for k in ("unacceptable", "reduce", "acceptable") if c[k])

    lines += [
        "Method and scope: [RISK_MANAGEMENT_PLAN.md](RISK_MANAGEMENT_PLAN.md). Risks are "
        "evaluated for the intended clinical use ([INTENDED_USE.md](INTENDED_USE.md)), not for "
        "today's research use, in which no patient decision is made. Probabilities marked "
        "*measured* come from generated reports; *estimated* ones are engineering judgement "
        "to be replaced by data.",
        "",
        f"**{len(hz)} hazards.** Before the risk controls: {counts(before)}. After: "
        f"{counts(after)}.",
        "",
    ]
    if after["unacceptable"]:
        lines += [
            f"**{after['unacceptable']} residual risks are unacceptable for clinical use.** "
            "This is why the software is restricted to research use (SR-01). The *needed* "
            "line of each hazard is the evidence or control that would lower it.",
            "",
        ]
    lines += ["## Risk policy", "", f"One use = {pol.use}.", ""]
    lines += _table(
        ["Severity", "Name", "Meaning"],
        [[k, v.name, v.meaning] for k, v in sorted(pol.severity.items())],
    ) + [""]
    lines += _table(
        ["Probability", "Name", "Meaning"],
        [[k, v.name, v.meaning] for k, v in sorted(pol.probability.items())],
    ) + [""]
    lines += [
        f"Risk index = severity × probability: ≤ {pol.acceptable_max} acceptable; "
        f"{pol.acceptable_max + 1}–{pol.unacceptable_min - 1} reduce as far as possible and "
        f"weigh against the benefit; ≥ {pol.unacceptable_min} unacceptable.",
        "",
    ]
    short = {"acceptable": "A", "reduce": "R", "unacceptable": "U"}
    lines += _table(
        ["Severity \\ probability"] + [f"P{p} {pol.probability[p].name}" for p in range(1, 6)],
        [
            [f"S{s} {pol.severity[s].name}"]
            + [f"{s * p} {short[pol.level(s, p)]}" for p in range(1, 6)]
            for s in range(5, 0, -1)
        ],
    ) + ["", "A: acceptable, R: reduce, U: unacceptable.", ""]
    lines += ["## Overview", ""]
    lines += _table(
        ["ID", "Hazard", "S", "P before", "Risk before", "Controls", "P after", "Risk after"],
        [
            [h.id, h.title, h.severity, h.probability, _risk(trace, h.severity, h.probability),
             ", ".join(h.controls), h.residual_probability,
             _risk(trace, h.severity, h.residual_probability)]
            for h in hz
        ],
    ) + [""]  # fmt: skip
    lines += ["## Hazards", ""]
    for h in hz:
        lines += _hazard_block(h, trace, req)
    return "\n".join(lines).rstrip() + "\n"


def _hazard_block(h: Hazard, trace: Trace, req: dict[str, Requirement]) -> list[str]:
    pol = trace.policy
    out = [
        f"### {h.id}: {h.title}",
        "",
        f"- **Cause / sequence of events:** {' '.join(h.cause.split())}",
        f"- **Hazardous situation:** {' '.join(h.situation.split())}",
        f"- **Harm:** {' '.join(h.harm.split())}",
        f"- **Before controls:** S{h.severity} {pol.severity[h.severity].name} × "
        f"P{h.probability} {pol.probability[h.probability].name} = "
        f"{_risk(trace, h.severity, h.probability)}. {' '.join(h.basis.split())}",
        "- **Controls:** " + "; ".join(f"{c} {req[c].title}" for c in h.controls),
        f"- **After controls:** P{h.residual_probability} "
        f"{pol.probability[h.residual_probability].name} = "
        f"{_risk(trace, h.severity, h.residual_probability)}. "
        f"{' '.join(h.residual_basis.split())}",
    ]
    if h.evidence:
        out.append("- **Evidence:** " + ", ".join(f"[{Path(p).name}]({UP}{p})" for p in h.evidence))
    out += [f"- **Needed:** {' '.join(h.needed.split())}", ""]
    return out


def render_traceability(trace: Trace) -> str:
    req = {r.id: r for r in trace.requirements}
    lines = _head(
        "Traceability (draft)",
        f"`{REQUIREMENTS_FILE.as_posix()}` and `{HAZARDS_FILE.as_posix()}`",
    )
    lines += [
        "Hazard → risk control → verification (ISO 14971 §7.2, IEC 62304 §7.3), then "
        "requirement → code → tests.",
        "",
        "## Hazards to risk controls",
        "",
    ]
    rows = []
    for h in trace.hazards:
        for c in h.controls:
            r = req[c]
            n_tests, n_reports = len(r.tests), len(r.reports)
            ver = ", ".join(
                s for s in (f"{n_tests} tests" if n_tests else "",
                            f"{n_reports} reports" if n_reports else "",
                            "inspection" if r.inspection else "",
                            "gap" if r.gap else "") if s
            )  # fmt: skip
            rows.append([h.id, c, r.title, ver, _status(r)])
    lines += _table(["Hazard", "Control", "Requirement", "Verification", "Status"], rows)
    lines += ["", "## Requirements to code and tests", ""]
    lines += _table(
        ["Requirement", "Code", "Tests", "Reports"],
        [
            [r.id, _code(r.code), ", ".join(_test_link(t) for t in r.tests) or "–",
             ", ".join(f"[{Path(p).name}]({UP}{p})" for p in r.reports) or "–"]
            for r in trace.requirements
        ],
    )  # fmt: skip
    gaps = [r for r in trace.requirements if r.gap]
    lines += ["", "## Open gaps", ""]
    lines += [f"- **{r.id} {r.title}:** {' '.join(r.gap.split())}" for r in gaps] or ["None."]
    controls_unverified = sorted(
        {c for h in trace.hazards for c in h.controls if not (req[c].tests or req[c].reports)}
    )
    if controls_unverified:
        lines += [
            "",
            "Risk controls verified by inspection only or not at all: "
            + ", ".join(controls_unverified)
            + ".",
        ]
    return "\n".join(lines).rstrip() + "\n"


def render_soup(root: Path, lock: Lock, trace: Trace) -> tuple[str, str]:
    """SOUP.md and the SBOM; raises ``ValueError`` if the SOUP list is inconsistent."""
    soup = load_soup(root)
    imports = third_party_imports(root)
    python = python_version(root)
    problems = check_soup(soup, lock, imports)
    hazard_ids = {h.id for h in trace.hazards}
    problems += [
        f"{SOUP_FILE}: {s.name}: unknown hazard {h}"
        for s in soup.soup
        for h in s.hazards
        if h not in hazard_ids
    ]
    problems += [
        f"{SOUP_FILE}: CPython {p.version} differs from .python-version ({python})"
        for p in soup.platform
        if p.name == "CPython" and p.version != python
    ]
    if problems:
        raise ValueError("SOUP check failed:\n- " + "\n- ".join(problems))
    packages = release_packages(lock, python)
    versions: dict[str, list[str]] = {}
    for p in packages:
        versions.setdefault(p.name, [])
        if p.version not in versions[p.name]:
            versions[p.name].append(p.version)
    runtime = [p for p in packages if p.scope == "runtime"]
    tools = [p for p in packages if p.scope == "development"]
    shipped = {p.name for p in runtime if p.direct}
    sources = f"`uv.lock` (SHA-256 `{lock.sha256[:16]}…`) and `{SOUP_FILE.as_posix()}`"
    lines = _head("SOUP list and software bill of materials (draft)", sources)
    lines += [
        "IEC 62304 §5.3.3–5.3.4 (SOUP requirements), §7.1.2–7.1.3 (SOUP anomalies), §8.1.2 "
        "(SOUP identification). Versions come from the lock file: exactly what `uv sync "
        "--all-extras` installs, for CPython "
        f"{python} on {' and '.join(PLATFORMS)}. The same list in CycloneDX 1.5: "
        "[sbom.cdx.json](sbom.cdx.json).",
        "",
        f"**{len(runtime)} packages are shipped** ({len(shipped)} declared directly, the rest "
        f"their dependencies); {len(tools)} more are development tools only. Every "
        "third-party module the code imports belongs to an entry below (checked).",
        "",
        "## Direct SOUP of the product",
        "",
    ]
    rows, tool_rows = [], []
    for s in soup.soup:
        files = set().union(*(imports.get(m, set()) for m in s.imports))
        row = [s.name, ", ".join(versions.get(normalise(s.name), ["–"])),
               ", ".join(software_items(files)) or "not imported", s.purpose, s.relied_on,
               ", ".join(s.hazards) or "–", s.anomalies]  # fmt: skip
        (rows if normalise(s.name) in shipped else tool_rows).append(row)
    header = ["Package", "Version", "Used in", "Purpose", "Relied on", "Hazards",
              "Anomaly review"]  # fmt: skip
    lines += _table(header, rows)
    lines += ["", "## Development and documentation tools (not shipped)", ""]
    lines += _table(header, tool_rows)
    lines += ["", "## Platform SOUP", ""]
    platform = [[p.name, p.version, p.purpose, p.notes or "–"] for p in soup.platform]
    lines += _table(["Item", "Version", "Purpose", "Notes"], platform)
    lines += ["", "## All shipped packages", ""]
    lines += _table(
        ["Package", "Version", "Platforms", "Declared directly", "Index"],
        [[p.name, p.version, ", ".join(p.platforms), "yes" if p.direct else "–",
          p.source.split("//")[-1].split("/")[0]] for p in runtime],
    )  # fmt: skip
    lines += ["", "## Development-only packages", ""]
    lines += _table(
        ["Package", "Version", "Platforms", "Declared directly"],
        [[p.name, p.version, ", ".join(p.platforms), "yes" if p.direct else "–"] for p in tools],
    )
    text = "\n".join(lines).rstrip() + "\n"
    return text, sbom_json(packages, lock, python)


def render_all(root: Path = Path(".")) -> dict[Path, str]:
    """Every generated document, keyed by its path relative to ``root``. Raises
    ``ValueError`` listing every broken reference."""
    trace = load_trace(root)
    soup_md, sbom = render_soup(root, Lock.read(root), trace)
    return {
        REG_DIR / "REQUIREMENTS.md": render_requirements(trace),
        REG_DIR / "HAZARD_ANALYSIS.md": render_hazards(trace),
        REG_DIR / "TRACEABILITY.md": render_traceability(trace),
        REG_DIR / "SOUP.md": soup_md,
        REG_DIR / "sbom.cdx.json": sbom,
    }


def write_all(root: Path = Path("."), check: bool = False) -> list[Path]:
    """Write the documents (``check``: write nothing). Returns the files that were written,
    or with ``check`` the files that are missing or differ from their sources."""
    changed = []
    for rel, text in render_all(root).items():
        path = root / rel
        old = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if old != text:
            changed.append(rel)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    return changed
