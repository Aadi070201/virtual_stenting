"""Evaluation of the tree surrogate against the tree solver (``vstent eval-tree-surrogate``, P3)
→ ``reports/tree_surrogate_eval.{md,json}`` + figures.

Errors are FFR differences to the tree solver on the synthetic ``test`` and ``ood`` trees: at
every sample of every real branch (*node*), at every branch outlet, at the main outlet and at
the side outlets. For context, the error that ignoring the side branches would make (the main
vessel alone with the single-vessel solver vs the tree solver) is shown next to it.
"""

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import torch

from vstent import DISCLAIMER, __version__
from vstent.config import CONFIG_FILENAME, META_FILENAME, git_info, load_config, load_yaml
from vstent.data.synth import load_split
from vstent.plotting import (
    INK_MUTED,
    INK_SECONDARY,
    SERIES_1,
    SERIES_2,
    new_figure,
    save_figure,
    style_axes,
)
from vstent.surrogate.train import resolve_device
from vstent.surrogate.tree_features import TREE_NORM_STATS, TreeNormStats, prepare_tree_inputs
from vstent.surrogate.tree_train import (
    SUMMARY,
    TreeSurrogateConfig,
    load_tree_checkpoint,
    load_tree_raw,
    predict_tree_batches,
)

TARGET_MAE = 0.015
CUTOFF = 0.80
SPLITS = ("test", "ood")


def _binary(pred: np.ndarray, true: np.ndarray) -> dict[str, float]:
    """Agreement at FFR ≤ 0.80 (solver = reference): sensitivity, specificity, accuracy."""
    p, t = pred <= CUTOFF, true <= CUTOFF
    return {
        "sensitivity": float((p & t).sum() / max(t.sum(), 1)),
        "specificity": float((~p & ~t).sum() / max((~t).sum(), 1)),
        "accuracy": float((p == t).mean()),
    }


def split_metrics(pred: np.ndarray, true: np.ndarray, mask: np.ndarray, single: np.ndarray,
                  branch_count: np.ndarray) -> dict[str, Any]:  # fmt: skip
    """All metrics of one split; arrays (B, M, N) except ``single`` (B, N) and counts (B,)."""
    err = np.abs(pred - true)
    outlet_err = err[..., -1][mask]
    side = mask.copy()
    side[:, 0] = False
    by_count = {}
    for k in range(2, mask.shape[1] + 1):
        sel = branch_count == k
        if sel.any():
            by_count[str(k - 1)] = {
                "n_trees": int(sel.sum()),
                "outlet_mae": float(err[sel][..., -1][mask[sel]].mean()),
                "node_mae": float(err[sel][mask[sel]].mean()),
            }
    return {
        "n_trees": int(len(pred)),
        "n_branches": int(mask.sum()),
        "node_mae": float(err[mask].mean()),
        "node_max": float(err[mask].max()),
        "outlet_mae": float(outlet_err.mean()),
        "outlet_p95": float(np.percentile(outlet_err, 95)),
        "outlet_max": float(outlet_err.max()),
        "main_outlet_mae": float(err[:, 0, -1].mean()),
        "side_outlet_mae": float(err[..., -1][side].mean()) if side.any() else None,
        "outlet_agreement": _binary(pred[..., -1][mask], true[..., -1][mask]),
        "single_path_main_outlet_mae": float(np.abs(single[:, -1] - true[:, 0, -1]).mean()),
        "by_side_branches": by_count,
    }


def plot_outlets(results: dict[str, dict[str, np.ndarray]], path: Path) -> None:
    """Outlet FFR, surrogate vs tree solver, test and ood (identity line, 0.80 cut-off)."""
    fig = new_figure(
        8.0, 4.2, "Tree surrogate vs tree solver: FFR at every branch outlet",
        "Synthetic test (in distribution) and ood trees; dashed = identity, dotted = 0.80",
    )  # fmt: skip
    axes = fig.subplots(1, 2, sharey=True, gridspec_kw={"wspace": 0.08})
    fig.subplots_adjust(left=0.08, right=0.98, top=0.80, bottom=0.14)
    for ax, (split, color) in zip(axes, (("test", SERIES_1), ("ood", SERIES_2)), strict=True):
        style_axes(ax)
        r = results[split]
        t, p = r["true"][..., -1][r["mask"]], r["pred"][..., -1][r["mask"]]
        ax.scatter(t, p, s=3, color=color, alpha=0.35, linewidths=0, rasterized=True)
        ax.plot([0, 1], [0, 1], color=INK_MUTED, lw=1.0, ls=(0, (4, 3)))
        for f in (ax.axhline, ax.axvline):
            f(CUTOFF, color=INK_MUTED, lw=0.8, ls=(0, (1, 2)))
        ax.set_xlim(0, 1.02)
        ax.set_ylim(0, 1.02)
        ax.set_title(f"{split} ({len(t):,} outlets)", loc="left", fontsize=8.5, color=INK_SECONDARY)
        ax.set_xlabel("Tree solver FFR", fontsize=8, color=INK_SECONDARY)
    axes[0].set_ylabel("Tree surrogate FFR", fontsize=8, color=INK_SECONDARY)
    save_figure(fig, path)


def _markdown(report: dict[str, Any]) -> str:
    s, prov = report["splits"], report["provenance"]
    yes = {True: "yes", False: "NO"}
    lines = [
        "# Tree surrogate evaluation (P3)",
        "",
        f"> **{DISCLAIMER}**",
        "",
        "Generated by `vstent eval-tree-surrogate`. Do not edit by hand. Errors are FFR "
        "differences to the tree solver (docs/PHYSICS.md, *Vessel trees*) on synthetic trees "
        "(`reports/tree_dataset_card.md`), not to invasive FFR.",
        "",
        "## Targets (test trees)",
        "",
        "| Metric | Value | Target | Pass |",
        "|---|---|---|---|",
    ]
    for t in report["targets"]:
        lines.append(f"| {t['metric']} | {t['value']:.4f} | ≤ {t['target']} | {yes[t['passed']]} |")
    lines += [
        "",
        "FFR(0) = 1 at the inlet, continuity at every junction and monotone decrease along every "
        "path hold by construction (the model's tree head).",
        "",
        "## All metrics",
        "",
        "| Metric | test | ood |",
        "|---|---|---|",
    ]
    rows = [
        ("Trees / branches", lambda x: f"{x['n_trees']:,} / {x['n_branches']:,}"),
        ("MAE, every sample of every branch", lambda x: f"{x['node_mae']:.4f}"),
        ("Max error, any sample", lambda x: f"{x['node_max']:.3f}"),
        ("MAE at every outlet", lambda x: f"{x['outlet_mae']:.4f}"),
        ("95th percentile / max error at outlets",
         lambda x: f"{x['outlet_p95']:.4f} / {x['outlet_max']:.3f}"),
        ("MAE at the main outlet", lambda x: f"{x['main_outlet_mae']:.4f}"),
        ("MAE at side outlets", lambda x: f"{x['side_outlet_mae']:.4f}"),
        ("Outlets: agreement at 0.80 (sensitivity / specificity / accuracy)",
         lambda x: "{sensitivity:.3f} / {specificity:.3f} / {accuracy:.3f}".format(
             **x["outlet_agreement"])),
        ("For context: main outlet, single-path solver vs tree solver (MAE)",
         lambda x: f"{x['single_path_main_outlet_mae']:.4f}"),
    ]  # fmt: skip
    for label, fmt in rows:
        lines.append(f"| {label} | {fmt(s['test'])} | {fmt(s['ood'])} |")
    lines += [
        "",
        "By number of side branches (test): "
        + "; ".join(
            f"{k}: {v['n_trees']:,} trees, outlet MAE {v['outlet_mae']:.4f}"
            for k, v in s["test"]["by_side_branches"].items()
        )
        + ".",
        "",
        "![Outlet FFR](figures/tree_surrogate_outlets.png)",
        "",
        "## Training",
        "",
        f"Run `{report['run']}`: {report['training']['epochs_run']} epochs, best at epoch "
        f"{report['training']['best_epoch']} (val outlet MAE "
        f"{report['training']['best_val_outlet_mae']:.4f}), "
        f"{report['training']['train_seconds'] / 60:.0f} min on "
        f"{report['training']['gpu'] or 'CPU'}, "
        f"{report['training']['n_parameters']:,} parameters.",
        "",
        "## Limitations",
        "",
        "- Agreement with the tree solver only; the solver's own error against 3D CFD or wire FFR "
        "is not measured here (P4, P6).",
        "- At most 5 branches (main + 4 side branches) of 256 samples each; image trees with more "
        "branches fall back to the solver.",
        "- `ood` trees (100–140 mm main vessel, 4 side branches) are outside the training ranges.",
        "",
        f"Evaluation commit `{prov['git_commit']}` (dirty: {prov['git_dirty']}), "
        f"vstent {prov['vstent_version']}, {prov['created_utc']}.",
        "",
    ]
    return "\n".join(lines)


def evaluate_tree_run(
    run_dir: str | Path, report_dir: str | Path = "reports", device: str = "auto"
) -> dict[str, Any]:
    """Evaluate a run's best model on ``test`` and ``ood``; write the report and figure."""
    provenance = {
        **git_info(),
        "vstent_version": __version__,
        "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    run_dir, report_dir = Path(run_dir), Path(report_dir)
    cfg = load_config(run_dir / CONFIG_FILENAME, TreeSurrogateConfig)
    stats = TreeNormStats.load(run_dir / TREE_NORM_STATS)
    dev = resolve_device(device)
    model = load_tree_checkpoint(run_dir, dev)
    splits, arrays = {}, {}
    for split in SPLITS:
        raw, true = load_tree_raw(cfg.data_dir, split)
        extra = load_split(cfg.data_dir, split, ("ffr_main_single", "branch_count"))
        xs = [torch.from_numpy(x).to(dev) for x in prepare_tree_inputs(raw, stats)]
        pred = predict_tree_batches(model, xs).cpu().numpy()
        splits[split] = split_metrics(pred, true, raw.mask, extra["ffr_main_single"],
                                      extra["branch_count"])  # fmt: skip
        arrays[split] = {"pred": pred, "true": true, "mask": raw.mask}
    plot_outlets(arrays, report_dir / "figures" / "tree_surrogate_outlets.png")
    test = splits["test"]
    targets = [
        {"metric": "MAE, every sample of every branch (node-wise)", "value": test["node_mae"],
         "target": TARGET_MAE, "passed": test["node_mae"] <= TARGET_MAE},
        {"metric": "MAE at every outlet (distal)", "value": test["outlet_mae"],
         "target": TARGET_MAE, "passed": test["outlet_mae"] <= TARGET_MAE},
    ]  # fmt: skip
    report = {
        "targets": targets,
        "targets_met": all(t["passed"] for t in targets),
        "splits": splits,
        "training": json.loads((run_dir / SUMMARY).read_text(encoding="utf-8")),
        "run": run_dir.as_posix(),
        "run_meta": load_yaml(run_dir / META_FILENAME),
        "provenance": provenance,
    }
    report_dir.mkdir(parents=True, exist_ok=True)
    (report_dir / "tree_surrogate_eval.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8", newline="\n"
    )
    (report_dir / "tree_surrogate_eval.md").write_text(
        _markdown(report), encoding="utf-8", newline="\n"
    )
    return report
